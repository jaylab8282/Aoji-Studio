import { describe, expect, it } from "vitest";
import { tokenText } from "./usageFormat";

describe("tokenText 토큰 수치 축약", () => {
  it.each([
    [0, "0"],
    [999, "999"],
    [1_000, "1.00K"],
    [12_340, "12.34K"],
    [999_999, "1.00M"],
    [1_000_000, "1.00M"],
    [38_200_000, "38.20M"],
    [38_201_234, "38.20M"],
    [999_995_000, "1.00B"],
    [1_000_000_000, "1.00B"],
    [1_234_560_000, "1.23B"],
    [1_234_000_000_000, "1,234.00B"],
    [1_005, "1.01K"],
    [999_994, "999.99K"],
    [999_995, "1.00M"],
    [999_994_999, "999.99M"],
    [1234.5, "1.23K"],
  ])("[FR-025-AC8] %i → %s", (value, text) => {
    expect(tokenText(value)).toBe(text);
  });
});
